    bank_name TEXT DEFAULT 'BCA',
    bank_account_number TEXT DEFAULT '0158923120',
    bank_account_holder TEXT DEFAULT 'Info Kost Solo Official',
    created_at TIMESTAMPTZ DEFAULT NOW()

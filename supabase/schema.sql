-- Trigger Otomatis: Menghitung koordinat Point PostGIS dari latitude & longitude
CREATE OR REPLACE FUNCTION public.sync_kost_location()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.latitude IS NOT NULL AND NEW.longitude IS NOT NULL THEN
        NEW.location := ST_SetSRID(ST_MakePoint(NEW.longitude, NEW.latitude), 4326);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_kost_location ON public.kosts;
CREATE TRIGGER trg_sync_kost_location
BEFORE INSERT OR UPDATE ON public.kosts
FOR EACH ROW
EXECUTE FUNCTION public.sync_kost_location();

-- Update data yang sudah ada sebelumnya (jika ada)
UPDATE public.kosts 
SET location = ST_SetSRID(ST_MakePoint(longitude, latitude), 4326) 
WHERE location IS NULL AND latitude IS NOT NULL AND longitude IS NOT NULL;

-- Index Spasial PostGIS GIST
CREATE INDEX IF NOT EXISTS idx_kosts_location ON public.kosts USING GIST (location);

-- 5. Tabel Rooms
CREATE TABLE IF NOT EXISTS public.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kost_id BIGINT REFERENCES public.kosts(id) ON DELETE CASCADE,
    room_number TEXT NOT NULL,
    price_per_month NUMERIC(12, 2) NOT NULL,
    facilities TEXT[] DEFAULT ARRAY['Kamar Mandi Dalam', 'Kasur Springbed', 'WiFi ID', 'AC'],
    is_available BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabel Bookings (Manual Transfer)
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT REFERENCES public.rooms(id) ON DELETE CASCADE,
    tenant_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    status booking_status DEFAULT 'menunggu_bukti',
    proof_of_payment_url TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

